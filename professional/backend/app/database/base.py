"""The declarative Base, the naming convention and the standard column mixins
(technical-architecture.md sections 9.1, 9.2 and 9.4).

Every Professional table lives in schema `professional`. The schema is set once on the
MetaData, so every table built from Base and every unqualified ForeignKey("users.id")
target lands there without repeating it in each model.

The naming convention names every constraint and index the same way, so Alembic never
creates an unnamed one (DR-09):

    pk_<table>                      primary key
    fk_<table>__<column>__<target>  foreign key
    uq_<table>__<columns>           unique constraint
    ck_<table>__<rule>              check constraint (name the rule: CheckConstraint(..., name="status"))
    ix_<table>__<columns>           index
"""

import os
import time
import uuid
from datetime import datetime

from sqlalchemy import DateTime, Integer, MetaData, Uuid, func, text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.core.config import PROFESSIONAL_SCHEMA

NAMING_CONVENTION = {
    "pk": "pk_%(table_name)s",
    "fk": "fk_%(table_name)s__%(column_0_N_name)s__%(referred_table_name)s",
    "uq": "uq_%(table_name)s__%(column_0_N_name)s",
    "ck": "ck_%(table_name)s__%(constraint_name)s",
    "ix": "ix_%(table_name)s__%(column_0_N_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(schema=PROFESSIONAL_SCHEMA, naming_convention=NAMING_CONVENTION)


def new_uuid7() -> uuid.UUID:
    """A UUIDv7 (RFC 9562): 48-bit Unix time in milliseconds, then random bits, so new
    keys are time-ordered and stay close together in the index (DB-01). Python 3.12 has
    no uuid.uuid7(), and PostgreSQL only gains uuidv7() in version 18."""
    unix_ms = time.time_ns() // 1_000_000
    random_bits = int.from_bytes(os.urandom(10), "big")
    value = (unix_ms & 0xFFFF_FFFF_FFFF) << 80
    value |= 0x7 << 76  # version 7
    value |= ((random_bits >> 62) & 0xFFF) << 64  # 12 random bits
    value |= 0b10 << 62  # RFC 9562 variant
    value |= random_bits & 0x3FFF_FFFF_FFFF_FFFF  # 62 random bits
    return uuid.UUID(int=value)


class UuidPrimaryKeyMixin:
    """`id uuid PRIMARY KEY`, generated by the application (DB-01). The database default
    `uuidv7()` (PostgreSQL 18) covers rows inserted outside the ORM; the Python default
    stays the main one."""

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=new_uuid7, server_default=text("uuidv7()"))


class CreatedAtMixin:
    """`created_at timestamptz NOT NULL DEFAULT now()`, on every table."""

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


class TimestampMixin(CreatedAtMixin):
    """`created_at` plus `updated_at`, set again on every update through the ORM."""

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )


class SoftDeleteMixin:
    """`deleted_at timestamptz NULL` for tables whose rows are kept after deletion
    (users, listings, projects; DB-07)."""

    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)


class VersionMixin:
    """`version integer NOT NULL DEFAULT 1` for rows edited concurrently (stock items),
    used for optimistic locking (SC-02)."""

    version: Mapped[int] = mapped_column(Integer, nullable=False, server_default="1", default=1)
