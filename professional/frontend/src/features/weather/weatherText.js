function fill(text, vars) {
  return vars ? text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] ?? match)) : text
}

export function useWeatherText() {
  const { language, td } = useLanguage()
  return useCallback((key, vars) => {
    const english = WEATHER_TEXT[key] ?? key
    // Placeholders are filled after translating, so a number is never sent for translation.
    return fill(language && language !== 'en' ? td(english) : english, vars)
  }, [language, td])
}
